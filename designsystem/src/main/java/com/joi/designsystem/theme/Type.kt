package com.joi.designsystem.theme

import androidx.compose.material3.Typography
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.sp

// Default system font family everywhere — a custom display font is a nice future touch (a
// rounded, slightly playful face would suit the 10-20 audience) but not worth the asset risk
// in a build no one has compiled yet.
